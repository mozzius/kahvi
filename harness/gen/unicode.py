#!/usr/bin/env python3
"""Generates crates/kahvi-unicode/src/tables.rs from the Unicode Character
Database. The version is pinned to what the pinned test262 expects.

    python3 harness/gen/unicode.py      # downloads UCD files into work/ucd/ (cached)
"""

import re
import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "work" / "ucd" / VERSION
OUT = ROOT / "crates" / "kahvi-unicode" / "src" / "tables.rs"


def fetch(name):
    path = CACHE / name
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = f"https://www.unicode.org/Public/{VERSION}/ucd/{name}"
        print(f"downloading {url}", file=sys.stderr)
        path.write_bytes(urllib.request.urlopen(url, timeout=60).read())
    return path.read_text(encoding="utf-8")


def property_ranges(text, wanted):
    ranges = []
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        cps, prop = [x.strip() for x in line.split(";")[:2]]
        if prop != wanted:
            continue
        lo, _, hi = cps.partition("..")
        ranges.append((int(lo, 16), int(hi or lo, 16)))
    ranges.sort()
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


def emit(name, ranges):
    body = "".join(f"    (0x{lo:X}, 0x{hi:X}),\n" for lo, hi in ranges)
    return f"pub static {name}: &[(u32, u32)] = &[\n{body}];\n"


def main():
    derived = fetch("DerivedCoreProperties.txt")
    out = [
        f"// Generated by harness/gen/unicode.py from Unicode {VERSION}. Do not edit.\n\n",
        f'pub const UNICODE_VERSION: &str = "{VERSION}";\n\n',
        emit("ID_START", property_ranges(derived, "ID_Start")),
        "\n",
        emit("ID_CONTINUE", property_ranges(derived, "ID_Continue")),
    ]
    OUT.write_text("".join(out))
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
