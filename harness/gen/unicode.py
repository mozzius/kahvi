#!/usr/bin/env python3
"""Generates crates/kahvi-unicode/src/tables.rs from the Unicode Character
Database. The version is pinned to what the pinned test262 expects.

    python3 harness/gen/unicode.py      # downloads UCD files into work/ucd/ (cached)

The tables cover what ECMAScript needs: identifier characters, the
properties RegExp property escapes accept (spec tables
table-nonbinary-unicode-properties, table-binary-unicode-properties and
table-binary-unicode-properties-of-strings), simple case folding, and the
unconditional full case mappings.
"""

import re
import sys
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
ROOT = Path(__file__).resolve().parents[2]
CACHE = ROOT / "work" / "ucd" / VERSION
OUT = ROOT / "crates" / "kahvi-unicode" / "src" / "tables.rs"
SPEC = ROOT / "vendor" / "ecma262"
MAX = 0x10FFFF


def fetch(name):
    path = CACHE / name
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        base = f"https://www.unicode.org/Public/{VERSION}/"
        url = base + (name if name.startswith(("emoji/", "ucd/")) else f"ucd/{name}")
        print(f"downloading {url}", file=sys.stderr)
        path.write_bytes(urllib.request.urlopen(url, timeout=60).read())
    return path.read_text(encoding="utf-8")


def data_lines(text):
    """(fields, comment) for every data line of a UCD file."""
    for line in text.splitlines():
        data, _, comment = line.partition("#")
        if data.strip():
            yield [f.strip() for f in data.split(";")], comment.strip()


def parse_cps(field):
    lo, _, hi = field.partition("..")
    return int(lo, 16), int(hi or lo, 16)


def merge(ranges):
    merged = []
    for lo, hi in sorted(ranges):
        if merged and lo <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


def property_ranges(text, wanted):
    return merge(parse_cps(f[0]) for f, _ in data_lines(text) if len(f) > 1 and f[1] == wanted)


def complement(ranges):
    out, nxt = [], 0
    for lo, hi in ranges:
        if lo > nxt:
            out.append((nxt, lo - 1))
        nxt = hi + 1
    if nxt <= MAX:
        out.append((nxt, MAX))
    return out


def spec_table(name):
    """The property names in one of the spec's property tables, grouped as
    [canonical, alias, ...]. A row's first cell is a name or alias; the
    canonical name is in the second cell, which spans the alias rows below."""
    text = (SPEC / f"{name}.html").read_text()
    groups = []
    for row in re.findall(r"<tr>(.*?)</tr>", text, re.S):
        cells = [re.findall(r"`([^`]+)`", c) for c in re.findall(r"<td[^>]*>(.*?)</td>", row, re.S)]
        if not cells:
            continue
        if len(cells) == 1 and groups and "rowspan" in prev_row:
            groups[-1].append(cells[0][0])
            continue
        canonical = cells[-1][0]
        groups.append([canonical] + [n for n in cells[0] if n != canonical])
        prev_row = row
    return groups


def rust_ranges(ranges):
    items = [f"(0x{lo:X}, 0x{hi:X})" for lo, hi in ranges]
    lines = ["    " + ", ".join(items[i : i + 6]) + "," for i in range(0, len(items), 6)]
    return "&[\n" + "\n".join(lines) + "\n]"


def rust_ident(name):
    return re.sub(r"[^A-Z0-9]", "_", name.upper())


def main():
    out = [
        f"// Generated by harness/gen/unicode.py from Unicode {VERSION}. Do not edit.\n\n",
        "#![allow(clippy::unreadable_literal)]\n\n",
        f'pub const UNICODE_VERSION: &str = "{VERSION}";\n\n',
        "/// A binary property of strings: its name, single code points and longer strings.\n",
        "pub type StringProperty = (&'static str, &'static [(u32, u32)], &'static [&'static [u32]]);\n\n",
    ]

    def static(name, ty, value):
        out.append(f"pub static {name}: {ty} = {value};\n\n")

    derived = fetch("DerivedCoreProperties.txt")
    static("ID_START", "&[(u32, u32)]", rust_ranges(property_ranges(derived, "ID_Start")))
    static("ID_CONTINUE", "&[(u32, u32)]", rust_ranges(property_ranges(derived, "ID_Continue")))

    # ---- General_Category: every code point, from the extracted file (Cn included).
    aliases = list(data_lines(fetch("PropertyValueAliases.txt")))
    gc_lines = [(f, c) for f, c in aliases if f[0] == "gc"]
    gc_values = [f[1] for f, c in gc_lines if "|" not in c]  # the leaf values: Lu, Ll, ...
    gc_index = {v: i for i, v in enumerate(gc_values)}
    gc_ranges = []
    for f, _ in data_lines(fetch("extracted/DerivedGeneralCategory.txt")):
        lo, hi = parse_cps(f[0])
        gc_ranges.append((lo, hi, gc_index[f[1]]))
    gc_ranges.sort()
    static("GC_VALUES", "&[&str]", "&[" + ", ".join(f'"{v}"' for v in gc_values) + "]")
    items = [f"(0x{lo:X}, 0x{hi:X}, {i})" for lo, hi, i in gc_ranges]
    static("GENERAL_CATEGORY", "&[(u32, u32, u8)]",
           "&[\n" + "\n".join("    " + ", ".join(items[i : i + 5]) + "," for i in range(0, len(items), 5)) + "\n]")
    # Each value name or alias, with the set of leaf values it stands for as a bit mask.
    gc_alias_rows = []
    for f, c in gc_lines:
        leaves = [x.strip() for x in c.split("|")] if "|" in c else [f[1]]
        mask = sum(1 << gc_index[x] for x in leaves)
        for name in f[1:]:
            gc_alias_rows.append((name, mask))
    static("GC_VALUE_ALIASES", "&[(&str, u32)]",
           "&[\n" + "".join(f'    ("{n}", 0x{m:X}),\n' for n, m in sorted(gc_alias_rows)) + "]")

    # ---- Script and Script_Extensions (values are the short names).
    sc_lines = [f for f, _ in aliases if f[0] == "sc"]
    sc_values = [f[1] for f in sc_lines]
    sc_index = {v: i for i, v in enumerate(sc_values)}
    long_to_short = {f[2]: f[1] for f in sc_lines}
    sc_ranges = []
    for f, _ in data_lines(fetch("Scripts.txt")):
        lo, hi = parse_cps(f[0])
        sc_ranges.append((lo, hi, sc_index[long_to_short[f[1]]]))
    sc_ranges.sort()
    static("SCRIPT_VALUES", "&[&str]", "&[" + ", ".join(f'"{v}"' for v in sc_values) + "]")
    items = [f"(0x{lo:X}, 0x{hi:X}, {i})" for lo, hi, i in sc_ranges]
    static("SCRIPT", "&[(u32, u32, u16)]",
           "&[\n" + "\n".join("    " + ", ".join(items[i : i + 5]) + "," for i in range(0, len(items), 5)) + "\n]")
    sc_alias_rows = [(name, sc_index[f[1]]) for f in sc_lines for name in f[1:]]
    static("SCRIPT_VALUE_ALIASES", "&[(&str, u16)]",
           "&[\n" + "".join(f'    ("{n}", {i}),\n' for n, i in sorted(sc_alias_rows)) + "]")
    scx = []
    for f, _ in data_lines(fetch("ScriptExtensions.txt")):
        lo, hi = parse_cps(f[0])
        scx.append((lo, hi, [sc_index[s] for s in f[1].split()]))
    scx.sort()
    static("SCRIPT_EXTENSIONS", "&[(u32, u32, &[u16])]",
           "&[\n" + "".join(f"    (0x{lo:X}, 0x{hi:X}, &{vals}),\n" for lo, hi, vals in scx) + "]")

    # ---- Binary properties (spec table-binary-unicode-properties).
    sources = {
        "PropList.txt": fetch("PropList.txt"),
        "DerivedCoreProperties.txt": derived,
        "extracted/DerivedBinaryProperties.txt": fetch("extracted/DerivedBinaryProperties.txt"),
        "DerivedNormalizationProps.txt": fetch("DerivedNormalizationProps.txt"),
        "emoji-data.txt": fetch("ucd/emoji/emoji-data.txt"),
    }
    cn = [(lo, hi) for lo, hi, i in gc_ranges if gc_values[i] == "Cn"]
    computed = {"Any": [(0, MAX)], "ASCII": [(0, 0x7F)], "Assigned": complement(merge(cn))}
    binary_rows = []
    for names in spec_table("table-binary-unicode-properties"):
        canonical = names[0]
        ranges = computed.get(canonical)
        if ranges is None:
            found = [property_ranges(text, canonical) for text in sources.values()]
            found = [r for r in found if r]
            assert len(found) == 1, f"binary property {canonical} found in {len(found)} files"
            ranges = found[0]
        ident = "BP_" + rust_ident(canonical)
        static(ident, "&[(u32, u32)]", rust_ranges(ranges))
        binary_rows += [(n, ident) for n in names]
    static("BINARY_PROPERTIES", "&[(&str, &[(u32, u32)])]",
           "&[\n" + "".join(f'    ("{n}", {i}),\n' for n, i in sorted(binary_rows)) + "]")

    # ---- Binary properties of strings (spec table-binary-unicode-properties-of-strings).
    seqs = {}
    for name in ("emoji/emoji-sequences.txt", "emoji/emoji-zwj-sequences.txt"):
        for f, _ in data_lines(fetch(name)):
            prop = f[1]
            if ".." in f[0]:
                lo, hi = parse_cps(f[0])
                strings = [[c] for c in range(lo, hi + 1)]
            else:
                strings = [[int(x, 16) for x in f[0].split()]]
            seqs.setdefault(prop, []).extend(strings)
    string_props = [n[0] for n in spec_table("table-binary-unicode-properties-of-strings")]
    seqs["RGI_Emoji"] = [s for p in string_props if p != "RGI_Emoji" for s in seqs[p]]
    string_rows = []
    for prop in string_props:
        singles = merge((s[0], s[0]) for s in seqs[prop] if len(s) == 1)
        multi = sorted({tuple(s) for s in seqs[prop] if len(s) > 1})
        ident = "SP_" + rust_ident(prop)
        static(ident + "_CPS", "&[(u32, u32)]", rust_ranges(singles))
        body = "".join("    &[" + ", ".join(f"0x{c:X}" for c in s) + "],\n" for s in multi)
        static(ident + "_STRINGS", "&[&[u32]]", "&[\n" + body + "]")
        string_rows.append((prop, ident))
    static("STRING_PROPERTIES", "&[StringProperty]",
           "&[\n" + "".join(f'    ("{n}", {i}_CPS, {i}_STRINGS),\n' for n, i in string_rows) + "]")

    # ---- Simple case folding (statuses C and S).
    folds = []
    for f, _ in data_lines(fetch("CaseFolding.txt")):
        if f[1] in ("C", "S"):
            folds.append((int(f[0], 16), int(f[2], 16)))
    folds.sort()
    items = [f"(0x{a:X}, 0x{b:X})" for a, b in folds]
    static("SIMPLE_CASE_FOLDING", "&[(u32, u32)]",
           "&[\n" + "\n".join("    " + ", ".join(items[i : i + 6]) + "," for i in range(0, len(items), 6)) + "\n]")

    # ---- Full case mappings: UnicodeData's simple mappings, overridden by the
    # unconditional entries of SpecialCasing.txt. Unused slots are 0.
    upper, lower = {}, {}
    ranges_open = None
    for line in fetch("UnicodeData.txt").splitlines():
        f = line.split(";")
        cp = int(f[0], 16)
        if f[12]:
            upper[cp] = [int(f[12], 16)]
        if f[13]:
            lower[cp] = [int(f[13], 16)]
    del ranges_open
    for f, _ in data_lines(fetch("SpecialCasing.txt")):
        if len(f) > 4 and f[4]:
            continue  # conditional (language or context): handled by callers
        cp = int(f[0], 16)
        lo = [int(x, 16) for x in f[1].split()]
        up = [int(x, 16) for x in f[3].split()]
        if lo != [cp]:
            lower[cp] = lo
        elif cp in lower:
            del lower[cp]
        if up != [cp]:
            upper[cp] = up
        elif cp in upper:
            del upper[cp]
    for name, table in (("TO_UPPERCASE", upper), ("TO_LOWERCASE", lower)):
        assert all(len(v) <= 3 for v in table.values())
        items = []
        for cp in sorted(table):
            v = table[cp] + [0] * (3 - len(table[cp]))
            items.append(f"(0x{cp:X}, [0x{v[0]:X}, 0x{v[1]:X}, 0x{v[2]:X}])")
        static(name, "&[(u32, [u32; 3])]",
               "&[\n" + "\n".join("    " + ", ".join(items[i : i + 3]) + "," for i in range(0, len(items), 3)) + "\n]")

    OUT.write_text("".join(out).rstrip() + "\n")
    print(f"wrote {OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
