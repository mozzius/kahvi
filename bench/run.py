#!/usr/bin/env python3
"""Benchmarks: Kahvi against other JavaScript engines on the same machine.

Workloads (see README.md):
  octane/NAME     an Octane benchmark in deterministic mode (fixed iteration
                  counts, seeded Math.random), run as one classic script; its
                  own self-checks must pass and every result line must print
  realworld/NAME  a realworld/cases module (ES modules + node_modules); its
                  stdout must equal the case's Node-recorded .out
  startup/empty   an empty script: process start-up and realm creation

A run that fails its check is reported as a failure, never as a time.

Engines are found on PATH and in ~/.jsvu/bin and ~/.esvu/bin. Kahvi is the
release build (built unless --kahvi-dir is given). Each result is also given
as a ratio to a baseline engine measured in the same run (QuickJS when found,
else node --jitless), so machine speed and noise mostly cancel.

  ./bench/run.py                         default workloads, every engine found
  ./bench/run.py --engines kahvi,quickjs octane/richards octane/splay
  ./bench/run.py --all                   also the large Octane workloads
  ./bench/run.py --runs 5 --json out.json --markdown out.md
  ./bench/run.py --list                  list workloads and engines found
  ./bench/run.py --merge a.json b.json --json out.json --markdown out.md
"""

import argparse
import json
import os
import platform
import shutil
import statistics
import subprocess
import sys
import tempfile
import threading
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
BUILD = HERE / "build"
OCTANE = HERE / "node_modules" / "benchmark-octane" / "lib" / "octane"
REALWORLD = ROOT / "realworld"

# Octane benchmark -> its source files after base.js, in Octane's run.js order.
OCTANE_FILES = {
    "richards": ["richards.js"],
    "deltablue": ["deltablue.js"],
    "crypto": ["crypto.js"],
    "raytrace": ["raytrace.js"],
    "earley-boyer": ["earley-boyer.js"],
    "regexp": ["regexp.js"],
    "splay": ["splay.js"],
    "navier-stokes": ["navier-stokes.js"],
    "pdfjs": ["pdfjs.js"],
    "mandreel": ["mandreel.js"],
    "gbemu": ["gbemu-part1.js", "gbemu-part2.js"],
    "code-load": ["code-load.js"],
    "box2d": ["box2d.js"],
    "zlib": ["zlib.js", "zlib-data.js"],
    "typescript": ["typescript.js", "typescript-input.js", "typescript-compiler.js"],
}
# The classic small kernels run by default; the large application workloads
# take minutes on an interpreter and run with --all.
OCTANE_DEFAULT = ["richards", "deltablue", "crypto", "raytrace", "earley-boyer", "regexp", "splay", "navier-stokes"]
# realworld cases that are long enough to time.
REALWORLD_DEFAULT = ["acorn", "marked", "prettier", "terser"]

OCTANE_DRIVER = """
// Generated by bench/run.py: run every registered suite once, with fixed
// iteration counts, and fail loudly if any benchmark reports an error.
var print = typeof print === "function" ? print : console.log;
var failures = 0;
BenchmarkSuite.config.doWarmup = false;
BenchmarkSuite.config.doDeterministic = true;
// Scale Octane's iteration counts (sized for JIT engines) by --scale.
BenchmarkSuite.suites.forEach(function (suite) {
  suite.benchmarks.forEach(function (b) {
    b.deterministicIterations = Math.max(1, Math.round(b.deterministicIterations * %(scale)s));
  });
});
BenchmarkSuite.RunSuites({
  NotifyResult: function (name, result) { print(name + ": ok"); },
  NotifyError: function (name, error) { print(name + ": error " + error); failures++; },
  NotifyScore: function (score) {}
});
if (failures > 0) throw new Error(failures + " benchmark(s) failed");
"""

# How to run a classic script and an ES module file on each engine. None:
# the engine cannot run that kind (it has no package resolver, say).
ENGINES = {
    "kahvi": {"script": ["{kahvi}", "{file}"], "module": ["{kahvi_run}", "{file}"]},
    "node": {"script": ["{bin}", "{file}"], "module": ["{bin}", "{file}"]},
    "node-jitless": {"script": ["{bin}", "--jitless", "{file}"], "module": ["{bin}", "--jitless", "{file}"]},
    "quickjs": {"script": ["{bin}", "--script", "{file}"], "module": None},
    "boa": {"script": ["{bin}", "{file}"], "module": None},
    "hermes": {"script": ["{bin}", "{file}"], "module": None},
}
ENGINE_BINARIES = {
    "node": ["node"],
    "node-jitless": ["node"],
    "quickjs": ["qjs", "quickjs"],
    "boa": ["boa"],
    "hermes": ["hermes"],
}


def find_binary(names):
    dirs = [Path.home() / ".jsvu" / "bin", Path.home() / ".esvu" / "bin"]
    for n in names:
        p = shutil.which(n)
        if p:
            return p
        for d in dirs:
            if (d / n).exists():
                return str(d / n)
    return None


def engine_version(name, binary):
    if name == "kahvi":
        r = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True)
        return "git " + r.stdout.strip()
    for flag in (["--version"], ["-version"]):
        try:
            r = subprocess.run([binary, *flag], capture_output=True, text=True, timeout=10, stdin=subprocess.DEVNULL)
        except (OSError, subprocess.TimeoutExpired):
            continue
        out = (r.stdout + r.stderr).strip().splitlines()
        if r.returncode == 0 and out:
            return out[0][:80]
    return "unknown"


class Workload:
    def __init__(self, name, kind, file, check):
        self.name, self.kind, self.file, self.check = name, kind, file, check


def write_built(path, text):
    """Write a generated workload file whole, so runs started side by side
    (bench/icount.py -j, or two at once) never read a half-written one."""
    BUILD.mkdir(exist_ok=True)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.{threading.get_ident()}")
    tmp.write_text(text)
    os.replace(tmp, path)


def octane_workload(name, scale):
    parts = [(OCTANE / "base.js").read_text()]
    parts += [(OCTANE / f).read_text() for f in OCTANE_FILES[name]]
    parts.append(OCTANE_DRIVER % {"scale": repr(scale)})
    path = BUILD / f"octane-{name}.js"
    write_built(path, "\n;\n".join(parts))

    def check(out):
        lines = [l for l in out.splitlines() if l.strip()]
        return bool(lines) and all(l.endswith(": ok") for l in lines)

    return Workload(f"octane/{name}", "script", path, check)


def realworld_workload(name):
    case = REALWORLD / "cases" / f"{name}.mjs"
    want = case.with_suffix(".out").read_text()
    return Workload(f"realworld/{name}", "module", case, lambda out: out == want)


def startup_workload():
    path = BUILD / "startup-empty.js"
    write_built(path, "")
    return Workload("startup/empty", "script", path, lambda out: out == "")


def all_workloads(include_all):
    names = ["startup/empty"]
    names += [f"octane/{n}" for n in (OCTANE_FILES if include_all else OCTANE_DEFAULT)]
    names += [f"realworld/{n}" for n in REALWORLD_DEFAULT]
    return names


def make_workload(name, scale):
    group, _, short = name.partition("/")
    if group == "octane" and short in OCTANE_FILES:
        return octane_workload(short, scale)
    if group == "realworld" and (REALWORLD / "cases" / f"{short}.mjs").exists():
        return realworld_workload(short)
    if name == "startup/empty":
        return startup_workload()
    sys.exit(f"bench: unknown workload {name} (see --list)")


def run_once(argv, cwd, env, timeout):
    """Wall time (s), exit status, stdout, stderr and peak RSS (KiB) of one run."""
    with tempfile.TemporaryFile() as out_f, tempfile.TemporaryFile() as err_f:
        timed_out = threading.Event()
        start = time.perf_counter()
        proc = subprocess.Popen(argv, cwd=cwd, env=env, stdout=out_f, stderr=err_f, stdin=subprocess.DEVNULL)

        def kill():
            timed_out.set()
            proc.kill()

        timer = threading.Timer(timeout, kill)
        timer.start()
        try:
            _, status, usage = os.wait4(proc.pid, 0)
        finally:
            timer.cancel()
        secs = time.perf_counter() - start
        proc.returncode = os.waitstatus_to_exitcode(status)
        if timed_out.is_set():
            return None, None, "", f"timeout after {timeout}s", None
        out_f.seek(0)
        err_f.seek(0)
        out = out_f.read().decode(errors="replace")
        err = err_f.read().decode(errors="replace")
    return secs, proc.returncode, out, err, usage.ru_maxrss


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("workloads", nargs="*", help="workload names (default: the default set)")
    ap.add_argument("--all", action="store_true", help="include the large Octane workloads")
    ap.add_argument("--engines", help="comma-separated engines (default: every engine found)")
    ap.add_argument("--kahvi-dir", help="directory holding kahvi and kahvi-run (default: build target/release)")
    ap.add_argument("--scale", type=float, default=0.05,
                    help="fraction of Octane's deterministic iteration counts to run (default 0.05)")
    ap.add_argument("--runs", type=int, default=3, help="timed runs per engine and workload (default 3)")
    ap.add_argument("--timeout", type=int, default=900, help="seconds per run (default 900)")
    ap.add_argument("--json", metavar="FILE", help="write results as JSON")
    ap.add_argument("--markdown", metavar="FILE", help="write the results table as Markdown")
    ap.add_argument("--list", action="store_true", help="list workloads and engines, then exit")
    ap.add_argument("--merge", nargs="+", metavar="FILE",
                    help="combine the --json files of runs over different workloads or engines")
    args = ap.parse_args()
    if args.merge:
        return merge(args)

    for d, what in ((HERE, "bench"), (REALWORLD, "realworld")):
        if not (d / "node_modules").is_dir():
            subprocess.run(["npm", "ci", "--ignore-scripts", "--no-audit", "--no-fund"], cwd=d, check=True)

    if args.kahvi_dir:
        kahvi_dir = Path(args.kahvi_dir).resolve()
    elif args.list:
        kahvi_dir = ROOT / "target" / "release"
    else:
        subprocess.run(["cargo", "build", "-q", "--release", "-p", "kahvi-cli", "-p", "kahvi-runtime"], cwd=ROOT,
                       check=True)
        kahvi_dir = ROOT / "target" / "release"

    found = {"kahvi": str(kahvi_dir / "kahvi")}
    for name, bins in ENGINE_BINARIES.items():
        b = find_binary(bins)
        if b:
            found[name] = b
    wanted = args.engines.split(",") if args.engines else list(ENGINES)
    for e in wanted:
        if e not in ENGINES:
            sys.exit(f"bench: unknown engine {e} (known: {', '.join(ENGINES)})")
    engines = [e for e in wanted if e in found]
    missing = [e for e in wanted if e not in found]

    names = args.workloads or all_workloads(args.all)
    if args.list:
        print("workloads:", " ".join(all_workloads(True)))
        print("engines found:", " ".join(f"{e}={found[e]}" for e in engines))
        if missing:
            print("engines not found:", " ".join(missing))
        return
    if missing:
        print(f"bench: not found, skipped: {', '.join(missing)}", file=sys.stderr)

    versions = {e: engine_version(e, found[e]) for e in engines}
    env = {"PATH": os.environ.get("PATH", ""), "TZ": "UTC", "HOME": os.environ.get("HOME", "")}
    results = []
    for name in names:
        w = make_workload(name, args.scale)
        for e in engines:
            template = ENGINES[e][w.kind]
            if template is None:
                continue
            argv = [a.format(file=str(w.file), bin=found[e], kahvi=found["kahvi"],
                             kahvi_run=str(kahvi_dir / "kahvi-run")) for a in template]
            times, rss, error = [], [], None
            for _ in range(args.runs):
                secs, status, out, err, rss_kib = run_once(argv, w.file.parent, env, args.timeout)
                if status is None:
                    error = err
                elif status != 0:
                    error = (err.strip().splitlines() or [f"exit {status}"])[-1][:200]
                elif not w.check(out):
                    error = "wrong output: " + (out.strip().splitlines() or ["<empty>"])[-1][:200]
                if error:
                    break
                times.append(secs)
                rss.append(rss_kib)
            r = {"workload": w.name, "engine": e}
            if error:
                r["error"] = error
                print(f"{w.name:28} {e:14} FAIL  {error}", flush=True)
            else:
                r["times"] = [round(t, 4) for t in times]
                r["median"] = round(statistics.median(times), 4)
                r["rss_kib"] = max(rss)
                print(f"{w.name:28} {e:14} {r['median']:9.3f}s  (runs {', '.join(f'{t:.3f}' for t in times)})"
                      + (f"  rss {r['rss_kib'] // 1024} MiB" if r.get("rss_kib") else ""), flush=True)
            results.append(r)

    baseline = "quickjs" if "quickjs" in engines else "node-jitless" if "node-jitless" in engines else None
    by = {(r["workload"], r["engine"]): r for r in results}
    for r in results:
        b = by.get((r["workload"], baseline)) if baseline else None
        if "median" in r and b and "median" in b and b["median"] > 0:
            r["ratio_to_baseline"] = round(r["median"] / b["median"], 3)

    table = markdown_table(names, engines, by, baseline)
    print("\n" + table)
    meta = {"date": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "machine": platform.platform(),
            "octane_scale": args.scale,
            "cpu": platform.processor() or platform.machine(), "runs": args.runs, "baseline": baseline,
            "engines": {e: {"path": found[e], "version": versions[e]} for e in engines}}
    if args.json:
        Path(args.json).write_text(json.dumps({"meta": meta, "results": results}, indent=1) + "\n")
    if args.markdown:
        Path(args.markdown).write_text(table + "\n")


def merge(args):
    """One result from several --json files, as CI writes them from parallel
    runners. Each file's ratios were taken against the baseline measured on
    its own runner, so every file must have the same baseline engine."""
    runs = [json.loads(Path(f).read_text()) for f in args.merge]
    metas = [r["meta"] for r in runs]
    for key in ("baseline", "octane_scale", "runs"):
        seen = {json.dumps(m.get(key)) for m in metas}
        if len(seen) != 1:
            sys.exit(f"bench: --merge: the runs differ in {key} ({', '.join(sorted(seen))})")
    engines = {}
    for m in metas:
        engines.update(m["engines"])
    engines = {e: engines[e] for e in ENGINES if e in engines}
    # A (workload, engine) pair measured twice (the baseline, run beside each
    # group of engines) is reported from the first file that has it.
    by = {}
    for run in runs:
        for r in run["results"]:
            by.setdefault((r["workload"], r["engine"]), r)
    order = {n: i for i, n in enumerate(all_workloads(True))}
    names = sorted({w for w, _ in by}, key=lambda n: (order.get(n, len(order)), n))
    results = [by[(n, e)] for n in names for e in engines if (n, e) in by]
    baseline = metas[0]["baseline"]
    machines = sorted({m["machine"] for m in metas})
    meta = {**metas[0], "date": min(m["date"] for m in metas), "machine": ", ".join(machines),
            "engines": engines, "merged_from": len(runs)}
    table = markdown_table(names, list(engines), by, baseline)
    print(table)
    if args.json:
        Path(args.json).write_text(json.dumps({"meta": meta, "results": results}, indent=1) + "\n")
    if args.markdown:
        Path(args.markdown).write_text(table + "\n")


def markdown_table(names, engines, by, baseline):
    head = "| Workload | " + " | ".join(engines) + " |"
    rows = [head, "|---" * (len(engines) + 1) + "|"]
    for n in names:
        cells = []
        for e in engines:
            r = by.get((n, e))
            if r is None:
                cells.append("–")
            elif "error" in r:
                cells.append("fail")
            else:
                ratio = f" ({r['ratio_to_baseline']}x)" if "ratio_to_baseline" in r and e != baseline else ""
                cells.append(f"{r['median']:.3f}s{ratio}")
        rows.append(f"| {n} | " + " | ".join(cells) + " |")
    note = f"Median wall time; ratio to {baseline} in brackets (lower is faster)." if baseline else "Median wall time."
    return "\n".join(rows) + "\n\n" + note


if __name__ == "__main__":
    main()
